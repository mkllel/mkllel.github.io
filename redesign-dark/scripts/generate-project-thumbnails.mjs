import { createHash } from 'node:crypto';
import { mkdir, readdir, rm, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';
import { loadEnv } from 'vite';

const root = fileURLToPath(new URL('../', import.meta.url));
const env = { ...loadEnv('production', root, 'VITE_'), ...process.env };
const projectId = env.VITE_FIREBASE_PROJECT_ID || 'my-portfolio-2ea55';
const output = new URL('../public/project-thumbnails/', import.meta.url);
const manifest = new URL('../src/data/projectThumbnails.ts', import.meta.url);

async function getResponse(url, options = {}) {
  const response = await fetch(url, { ...options, signal: AbortSignal.timeout(60_000) });
  if (!response.ok) throw new Error(`Thumbnail request failed: HTTP ${response.status}`);
  return response;
}

// Read only public documents. Never change the original images or Firestore data.
const response = await getResponse(
  `https://firestore.googleapis.com/v1/projects/${encodeURIComponent(projectId)}/databases/(default)/documents:runQuery`,
  {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ structuredQuery: {
      from: [{ collectionId: 'portfolioProjects' }],
      where: { fieldFilter: { field: { fieldPath: 'isPrivate' }, op: 'EQUAL', value: { booleanValue: false } } },
    } }),
  },
);
const rows = await response.json();
if (!Array.isArray(rows)) throw new Error('Invalid public project query response');
const urls = new Set();
for (const { document } of rows) {
  if (!document) continue;
  const fields = document.fields;
  const images = (fields.galleryImages?.arrayValue?.values || [])
    .map(image => image.mapValue?.fields?.url?.stringValue);
  images.push(fields.imageUrl?.stringValue);
  [...new Set(images.filter(Boolean))].slice(0, 2).forEach(url => urls.add(url));
}

await mkdir(output, { recursive: true });
const entries = {};
const generated = new Set();
let originalBytes = 0;
let smallBytes = 0;
let largeBytes = 0;
for (const url of [...urls].sort()) {
  if (new URL(url).protocol !== 'https:') throw new Error('Thumbnail sources must use HTTPS');
  const source = Buffer.from(await (await getResponse(url)).arrayBuffer());
  const hash = createHash('sha256').update(source).update('webp-q82-v1').digest('hex').slice(0, 20);
  const variants = [];
  for (const width of [480, 960]) {
    const { data, info } = await sharp(source).rotate()
      .resize({ width, withoutEnlargement: true })
      .webp({ quality: 82, effort: 6 }).toBuffer({ resolveWithObject: true });
    if (variants.some(variant => variant.width === info.width)) continue;
    const name = `${hash}-${info.width}.webp`;
    await writeFile(new URL(name, output), data);
    generated.add(name);
    variants.push({ src: `/project-thumbnails/${name}`, width: info.width, bytes: data.length });
  }
  entries[url] = {
    src: variants[0].src,
    srcSet: variants.map(variant => `${variant.src} ${variant.width}w`).join(', '),
  };
  originalBytes += source.length;
  smallBytes += variants[0].bytes;
  largeBytes += variants.at(-1).bytes;
}

await writeFile(manifest,
  '// Generated by npm run thumbnails. Original URLs remain unchanged in Firebase.\n'
  + 'const projectThumbnails: Record<string, { src: string; srcSet: string }> = '
  + JSON.stringify(entries, null, 2) + ';\n\nexport default projectThumbnails;\n');

// Remove only this generator's obsolete assets after the new manifest is ready.
for (const name of await readdir(output)) {
  if (/^[a-f0-9]{20}-\d+\.webp$/.test(name) && !generated.has(name)) await rm(new URL(name, output));
}
console.log(JSON.stringify({ images: urls.size, originalBytes, smallBytes, largeBytes }, null, 2));
